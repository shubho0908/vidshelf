import { chromium } from 'playwright';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 360, height: 800 }, isMobile: true, hasTouch: true });
const pg = await ctx.newPage();
await pg.goto('http://localhost:4173/', { waitUntil: 'networkidle' });
await pg.waitForTimeout(500);
await pg.screenshot({ path: '/tmp/phone360-library.png' });
await pg.locator('.aspect-video').first().tap();
await pg.waitForSelector('header h1', { timeout: 5000 });
await pg.waitForTimeout(500);
const hdr = await pg.evaluate(() => {
  const h = document.querySelector('header');
  const btns = [...h.querySelectorAll('button')];
  const tops = btns.map(k => k.getBoundingClientRect().top);
  const rows = tops.filter(t => Math.abs(t - tops[0]) > 20).length + 1;
  return { rows, beyond: btns.some(k => k.getBoundingClientRect().right > 360) };
});
console.log('360px player header rows:', hdr.rows, 'overflow:', hdr.beyond);
await pg.screenshot({ path: '/tmp/phone360-player.png' });
await b.close();
